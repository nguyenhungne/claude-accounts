import fs from 'node:fs';
import path from 'node:path';
import { isFile, writeTextAtomically } from '../fileSystem/FileSystem.js';
import { findExecutable } from '../platform/ExecutableLocator.js';
import { configHomeDirectory, homeDirectory } from '../platform/Platform.js';

const GITHUB_CREDENTIAL_HOSTS = ['https://github.com', 'https://gist.github.com'];
const GENERATED_FILE_HEADER = '# Generated by cct on every launch from profile.json. Edit gitconfig (same folder) instead.';
const USER_FILE_TEMPLATE = [
  '[include]',
  '\tpath = gitconfig.cct',
  '# Your own settings for this profile go below (git config --global writes here too).',
  '',
].join('\n');

const toGitPath = filePath => filePath.replace(/\\/g, '/');
const toGitValue = value => `"${String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

export class GitConfigWriter {
  constructor(directories) {
    this.directories = directories;
  }

  write(profile) {
    const generatedFile = this.directories.gitGeneratedConfigFile(profile);
    const generatedContent = `${this.#generatedLines(profile).join('\n')}\n`;
    if (!isFile(generatedFile) || fs.readFileSync(generatedFile, 'utf8') !== generatedContent) {
      writeTextAtomically(generatedFile, generatedContent);
    }
    const userFile = this.directories.gitGlobalConfigFile(profile);
    if (!isFile(userFile)) writeTextAtomically(userFile, USER_FILE_TEMPLATE);
  }

  #generatedLines(profile) {
    const lines = [GENERATED_FILE_HEADER];
    for (const baseConfigFile of this.#baseConfigFiles()) {
      lines.push('[include]', `\tpath = ${toGitValue(toGitPath(baseConfigFile))}`);
    }
    const { name, email } = profile.gitIdentity;
    if (name || email) {
      lines.push('[user]');
      if (name) lines.push(`\tname = ${toGitValue(name)}`);
      if (email) lines.push(`\temail = ${toGitValue(email)}`);
    }
    if (profile.isolates('gh')) {
      const credentialHelper = this.#githubCredentialHelper();
      for (const host of GITHUB_CREDENTIAL_HOSTS) {
        lines.push(`[credential "${host}"]`, '\thelper =', `\thelper = ${credentialHelper}`);
      }
    }
    return lines;
  }

  #baseConfigFiles() {
    const candidates = [path.join(configHomeDirectory(), 'git', 'config'), path.join(homeDirectory, '.gitconfig')];
    return candidates.filter(isFile);
  }

  #githubCredentialHelper() {
    const githubCli = findExecutable('gh');
    return githubCli ? `!'${toGitPath(githubCli)}' auth git-credential` : '!gh auth git-credential';
  }
}
